<?php
/**
 * Remove mPDF's optional fonts from vendor-prefixed/ so the plugin ships only DejaVu.
 *
 * The removed files form the downloadable font packs listed in src/render/font-packs.php. Each run checks
 * the installed files against that manifest first, so an mPDF update that changes the fonts stops the build
 * instead of shipping packs whose downloads no longer match.
 *
 * Usage:
 *   php bin/trim-fonts.php                   Check, then delete the pack fonts (runs after Strauss).
 *   php bin/trim-fonts.php --write-manifest  Rebuild the manifest from an untrimmed mPDF.
 *
 * After an mPDF update: rm -rf vendor-prefixed, WPBOOK_KEEP_FONTS=1 composer install,
 * php bin/trim-fonts.php --write-manifest, then composer install again.
 *
 * @package WPBook
 */

// phpcs:disable WordPress.WP.AlternativeFunctions, WordPress.Security.EscapeOutput -- command-line build script.

$root     = dirname( __DIR__ );
$fonts    = $root . '/vendor-prefixed/mpdf/mpdf/ttfonts';
$manifest = $root . '/src/render/font-packs.php';

/**
 * Fonts in the Chinese, Japanese and Korean pack. Every other non-DejaVu font is in the world pack.
 */
$cjk = array( 'Sun-ExtA.ttf', 'Sun-ExtB.ttf', 'UnBatang_0613.ttf' );

if ( in_array( '--write-manifest', $argv, true ) ) {
	$lock    = json_decode( (string) file_get_contents( $root . '/composer.lock' ), true );
	$version = '';
	foreach ( $lock['packages'] as $package ) {
		if ( 'mpdf/mpdf' === $package['name'] ) {
			$version = $package['version'];
		}
	}
	if ( '' === $version || ! is_dir( $fonts ) ) {
		fwrite( STDERR, "mPDF or its fonts not found. Run composer install first.\n" );
		exit( 1 );
	}
	$packs = array(
		'cjk'   => array(),
		'world' => array(),
	);
	$names = array_map( 'basename', glob( $fonts . '/*.{ttf,otf}', GLOB_BRACE ) );
	sort( $names );
	foreach ( $names as $name ) {
		if ( 0 === strpos( $name, 'DejaVu' ) ) {
			continue;
		}
		$packs[ in_array( $name, $cjk, true ) ? 'cjk' : 'world' ][ $name ] = array(
			'size'   => filesize( $fonts . '/' . $name ),
			'sha256' => hash_file( 'sha256', $fonts . '/' . $name ),
		);
	}
	$data = array(
		'mpdf'   => $version,
		'source' => 'https://raw.githubusercontent.com/mpdf/mpdf/' . $version . '/ttfonts/',
		'packs'  => $packs,
	);
	$php  = "<?php\n/**\n * Downloadable font packs: mPDF's optional fonts, with their sizes and SHA-256 hashes.\n *\n"
		. " * Generated by bin/trim-fonts.php --write-manifest. Do not edit.\n *\n * @package WPBook\n */\n\n"
		. 'return ' . var_export( $data, true ) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export -- code generation.
	file_put_contents( $manifest, $php );
	printf( "Wrote %s for mPDF %s: %d CJK and %d world fonts.\n", $manifest, $version, count( $packs['cjk'] ), count( $packs['world'] ) );
	exit( 0 );
}

if ( getenv( 'WPBOOK_KEEP_FONTS' ) ) {
	echo "WPBOOK_KEEP_FONTS is set: keeping all mPDF fonts.\n";
	exit( 0 );
}
if ( ! is_dir( $fonts ) ) {
	fwrite( STDERR, "No vendor-prefixed mPDF fonts to trim.\n" );
	exit( 0 );
}

$data    = require $manifest;
$listed  = array();
$errors  = array();
$removed = 0;
foreach ( $data['packs'] as $files ) {
	$listed += $files;
}

// Every optional font in mPDF must be in a pack, and every pack file must match its hash.
foreach ( glob( $fonts . '/*.{ttf,otf}', GLOB_BRACE ) as $path ) {
	$name = basename( $path );
	if ( 0 === strpos( $name, 'DejaVu' ) ) {
		continue;
	}
	if ( ! isset( $listed[ $name ] ) ) {
		$errors[] = "$name is not in a font pack";
	} elseif ( hash_file( 'sha256', $path ) !== $listed[ $name ]['sha256'] ) {
		$errors[] = "$name does not match the manifest";
	}
}
if ( $errors ) {
	fwrite( STDERR, "Font manifest is out of date (mPDF updated?):\n  " . implode( "\n  ", $errors ) . "\nRun: php bin/trim-fonts.php --write-manifest\n" );
	exit( 1 );
}

foreach ( array_keys( $listed ) as $name ) {
	if ( file_exists( $fonts . '/' . $name ) ) {
		unlink( $fonts . '/' . $name );
		++$removed;
	}
}
printf( "Trimmed %d optional fonts from mPDF.\n", $removed );
